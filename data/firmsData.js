const FIRMS_DATA_HELPER = {
  getRulesByModule: (moduleId) => {
    return RAW_RULES_DATA.filter(r => r.module === moduleId);
  },
  getUniversalRules: () => {
    return RAW_RULES_DATA.filter(r => r.module === "universal");
  },
  getRuleById: (ruleId) => {
    return RAW_RULES_DATA.find(r => r.id === ruleId);
  },
  getWorstCaseRulesForModule: (moduleId) => {
    const moduleRules = RAW_RULES_DATA.filter(r => r.module === moduleId);
    return moduleRules.filter(r => r.isWorstCase);
  }
};

